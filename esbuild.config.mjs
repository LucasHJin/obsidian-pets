import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { petAssetsEsbuildPlugin } from "./scripts/pet-assets.mjs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	plugins: [petAssetsEsbuildPlugin()],
	loader: {
		".png": "dataurl",
		".jpg": "dataurl",
		".jpeg": "dataurl",
		".gif": "dataurl",
		".svg": "dataurl",
		".mp3": "dataurl",
		".wav": "dataurl",
		".ogg": "dataurl",
	},
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
